import {
  arr,
  num,
  obj,
  type OutputSchema,
  str
} from '../../schema-builders.js';

export const tarotOutputSchema: OutputSchema = obj({
  问卜设定: obj({
    牌阵: str('使用的牌阵名称'),
    问题: str('占问事项'),
    出生日期: str('求问者出生日期（用于生命数字计算）'),
    随机种子: str('随机种子（用于复现抽牌结果）'),
  }, '问卜设定'),
  牌阵展开: arr(obj({
    位置: str('牌阵位置名称（如"过去"、"现在"、"未来"等）'),
    塔罗牌: str('抽到的塔罗牌名称'),
    状态: str('牌的状态（正位/逆位）'),
    核心基调: arr(str(), '当前正逆位下的牌义关键词'),
    元素: str('对应元素（火/水/风/土）'),
    星象: str('对应星体或星座'),
  }), '牌阵展开的各位置牌'),
  求问者生命数字: obj({
    人格牌: obj({
      对应塔罗: str('人格牌对应的塔罗牌'),
      背景基调: arr(str(), '牌义关键词'),
      元素: str('对应元素'),
      星象: str('对应星体或星座'),
    }, '人格牌'),
    灵魂牌: obj({
      对应塔罗: str('灵魂牌对应的塔罗牌'),
      背景基调: arr(str(), '牌义关键词'),
      元素: str('对应元素'),
      星象: str('对应星体或星座'),
    }, '灵魂牌'),
    年度牌: obj({
      对应塔罗: str('年度牌对应的塔罗牌'),
      年份: num('年度牌对应的公历年份'),
      背景基调: arr(str(), '牌义关键词'),
      元素: str('对应元素'),
      星象: str('对应星体或星座'),
    }, '年度牌'),
  }, '求问者生命数字（需提供出生日期）'),
});
