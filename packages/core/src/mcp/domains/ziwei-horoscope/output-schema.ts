import {
  arr,
  num,
  obj,
  type OutputSchema,
  str
} from '../../schema-builders.js';

export const ziweiHoroscopeOutputSchema: OutputSchema = obj({
  基本信息: obj({
    目标日期: str("查询的目标日期（公历）"),
    五行局: str("命主五行局（水二局/木三局/金四局/土五局/火六局）"),
    阳历: str("本命出生公历日期"),
    农历: str("本命出生农历日期"),
    命主: str("命主（命宫所在地支）"),
    身主: str("身主（身宫所在地支）"),
  }, "本命与目标日期基本信息"),
  运限叠宫: arr(obj({
    层次: str("运限层次（本命/大限/流年/流月/流日/流时等）"),
    时间段备注: str("该层次对应的时间段或备注"),
    宫位索引: num("宫位索引（0-11）"),
    干支: str("该层次宫位的干支"),
    落入本命宫位: str("该层次命宫落入本命盘的哪个宫位"),
    运限四化: arr(str(), "该层次宫干化出的四化星曜"),
    十二宫重排: arr(str(), "该层次的十二宫重排顺序（从该层次命宫起）"),
    流曜: arr(obj({ 宫位索引: num(), 星曜: str(), 类型: str(), 亮度: str(), 四化: str() })),
  }), "运限叠宫（本命、大限、流年、流月、流日、流时等各层次的宫位叠加）"),
  流年星曜: obj({
    吉星分布: arr(str(), "流年吉星在各宫的分布"),
    煞星分布: arr(str(), "流年煞星在各宫的分布"),
    '桃花/文星': arr(str(), "流年桃花星与文星在各宫的分布"),
  }, "流年星曜分布"),
  岁前十二星: arr(str(), "岁前十二星在各宫的分布（太岁、晦气、丧门等）"),
  将前十二星: arr(str(), "将前十二星在各宫的分布（博士、力士、青龙等）"),
});
