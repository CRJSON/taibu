#!/usr/bin/env node
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { requireGuide, SKILL_DIR, shortDescription } from './skill-guides.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const target = path.join(root, 'src/lib/agent/analysis-methods.generated.ts');

export function skillConventions(source) {
  const conventions = /(?:^|\n)## 约定[ \t]*\r?\n([\s\S]*?)(?=\r?\n## |$)/.exec(source)?.[1].trim();
  if (!conventions) throw new Error('SKILL.md 缺少约定段');
  return conventions;
}

export async function analysisMethodsSource() {
  const { listToolDefinitions } = await import(pathToFileURL(path.join(root, 'packages/core/dist/mcp/index.js')).href);
  const guides = {};
  const methods = listToolDefinitions().map(tool => {
    const guide = requireGuide(tool.name);
    if (!guides[guide]) {
      const body = readFileSync(path.join(SKILL_DIR, 'interpretation', `${guide}.md`), 'utf8');
      const title = /^#\s+(.+)$/m.exec(body)?.[1];
      if (!title || !body.trim()) throw new Error(`解读指引 ${guide} 缺少标题或正文`);
      guides[guide] = { title, body };
    }
    return { id: tool.name, guide, tool: tool.name, title: tool.title, whenToUse: shortDescription(tool.description) };
  });
  const skill = readFileSync(path.join(SKILL_DIR, 'SKILL.md'), 'utf8');
  const conventions = skillConventions(skill);
  return '// Generated by scripts/build-analysis-methods.mjs; do not edit.\n'
    + `export const ANALYSIS_GUIDES = ${JSON.stringify(guides, null, 2)} as const;\n`
    + `export const ANALYSIS_METHODS = ${JSON.stringify(methods, null, 2)} as const;\n`
    + `export const ANALYSIS_CONVENTIONS = ${JSON.stringify(conventions)};\n`;
}

if (process.argv[1] && pathToFileURL(path.resolve(process.argv[1])).href === import.meta.url) {
  const source = await analysisMethodsSource();
  if (process.argv.includes('--check')) {
    if (readFileSync(target, 'utf8') !== source) {
      console.error('Agent 解读知识产物已漂移，请运行 pnpm build:methods');
      process.exitCode = 1;
    }
  } else writeFileSync(target, source);
}
